const LANGUAGES = [
  { id: 'ar', locale: 'ar', label: 'العربية', english: 'Arabic', pack: 'ar' },
  { id: 'en', locale: 'en', label: 'English', english: 'English', pack: null },
  { id: 'fr', locale: 'fr', label: 'Français', english: 'French', pack: 'fr' },
  { id: 'ja', locale: 'ja', label: '日本語', english: 'Japanese', pack: 'ja' },
  { id: 'zh', locale: 'zh-cn', label: '中文 (简体)', english: 'Chinese (Simplified)', pack: 'zh-hans' },
  { id: 'de', locale: 'de', label: 'Deutsch', english: 'German', pack: 'de' }
];

function resolveLang(vscodeLanguage) {
  const l = String(vscodeLanguage || 'en').toLowerCase();
  if (l.startsWith('zh')) return 'zh';
  const base = l.split('-')[0];
  return S[base] ? base : 'en';
}

let current = 'en';
function setLanguage(vscodeLanguage) { current = resolveLang(vscodeLanguage); return current; }
function getLanguage() { return current; }
function isRtl() { return current === 'ar'; }

function t(key, ...args) {
  const table = S[current] || S.en;
  let s = table[key];
  if (s === undefined) s = S.en[key];
  if (s === undefined) return key;
  return s.replace(/\{(\d+)\}/g, (_, i) => (args[+i] !== undefined ? String(args[+i]) : ''));
}

module.exports = { S, LANGUAGES, resolveLang, setLanguage, getLanguage, isRtl, t };
